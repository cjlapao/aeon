// Command protogen derives the app's wire types from the Go method table and
// committed conformance examples. Examples establish observed fields; they do
// not claim to describe optional fields absent from every fixture.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
)

type fixture struct {
	Method       string         `json:"method"`
	Request      map[string]any `json:"request"`
	Response     map[string]any `json:"response"`
	Notification map[string]any `json:"notification"`
}

type samples struct {
	params  []any
	results []any
}

func main() {
	check := flag.Bool("check", false, "fail if the checked-in file differs")
	flag.Parse()
	content, err := generate("internal/protocol", "internal/protocol/conformance")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	out := "ui/src/proto/contract.ts"
	if *check {
		old, err := os.ReadFile(out)
		if err != nil || !bytes.Equal(old, content) {
			fmt.Fprintf(os.Stderr, "%s is stale; run make protogen\n", out)
			os.Exit(1)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(out), 0755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(out, content, 0644); err != nil {
		panic(err)
	}
}

// generate builds the app's wire types. methodsPath is the Go PACKAGE that
// declares the MethodName constants (see methodNames), not one shared file.
func generate(methodsPath, fixturesDir string) ([]byte, error) {
	methods, err := methodNames(methodsPath)
	if err != nil {
		return nil, err
	}
	byMethod := make(map[string]*samples)
	events := make(map[string]bool)
	protocolDir := filepath.Dir(fixturesDir)
	if err := sourceEventNames(protocolDir, filepath.Join(protocolDir, "..", "runtime"), events); err != nil {
		return nil, err
	}
	err = filepath.WalkDir(fixturesDir, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".json") {
			return nil
		}
		// This fixture deliberately contains unknown future fields. It tests
		// permissive decoders; those fields are not part of today's client type.
		if filepath.Base(path) == "forward-compat.json" {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var f fixture
		if err := json.Unmarshal(data, &f); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if f.Method != "" {
			entry := byMethod[f.Method]
			if entry == nil {
				entry = &samples{}
				byMethod[f.Method] = entry
			}
			if requestMethod, ok := f.Request["method"].(string); ok && requestMethod == f.Method {
				params, exists := f.Request["params"]
				if !exists || params == nil {
					params = map[string]any{}
				}
				entry.params = append(entry.params, params)
			}
			if result, ok := f.Response["result"]; ok {
				entry.results = append(entry.results, result)
			}
		}
		if params, ok := f.Notification["params"].(map[string]any); ok {
			if kind, ok := params["kind"].(string); ok {
				events[kind] = true
			}
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	var missing []string
	for _, name := range methods {
		entry := byMethod[name]
		if entry == nil || len(entry.params) == 0 || len(entry.results) == 0 {
			missing = append(missing, name)
		}
	}
	if len(missing) != 0 {
		return nil, fmt.Errorf("methods without request/result fixtures: %s", strings.Join(missing, ", "))
	}
	var b strings.Builder
	b.WriteString("// Generated by go run ./tools/protogen. Do not edit.\n")
	b.WriteString("// Types describe fields observed in conformance fixtures. Fields never present\n")
	b.WriteString("// in a fixture remain uncovered; Go remains the full protocol contract.\n\n")
	b.WriteString("export interface RpcMethods {\n")
	for _, name := range methods {
		entry := byMethod[name]
		fmt.Fprintf(&b, "  %q: { params: %s; result: %s };\n", name, tsType(entry.params, 2), tsType(entry.results, 2))
	}
	b.WriteString("}\n\n")
	var kinds []string
	for kind := range events {
		kinds = append(kinds, kind)
	}
	sort.Strings(kinds)
	b.WriteString("export const knownEventKinds = [\n")
	for _, kind := range kinds {
		fmt.Fprintf(&b, "  %q,\n", kind)
	}
	b.WriteString("] as const;\n")
	b.WriteString("export type KnownEventKind = (typeof knownEventKinds)[number];\n")
	b.WriteString("const knownEventKindSet: ReadonlySet<string> = new Set(knownEventKinds);\n")
	b.WriteString("export function isKnownEventKind(value: unknown): value is KnownEventKind {\n")
	b.WriteString("  return typeof value === \"string\" && knownEventKindSet.has(value);\n}\n")
	return []byte(b.String()), nil
}

// Event kinds also come from Go declarations and emission sites. Fixtures are
// deliberately partial for streamed step events, so a fixture-only allowlist
// would discard events that the daemon already emits.
func sourceEventNames(protocolDir, runtimeDir string, out map[string]bool) error {
	for _, dir := range []string{protocolDir, runtimeDir} {
		packages, err := parser.ParseDir(token.NewFileSet(), dir, func(info os.FileInfo) bool {
			return strings.HasSuffix(info.Name(), ".go") && !strings.HasSuffix(info.Name(), "_test.go")
		}, 0)
		if err != nil {
			return err
		}
		for _, pkg := range packages {
			for _, file := range pkg.Files {
				ast.Inspect(file, func(node ast.Node) bool {
					if spec, ok := node.(*ast.ValueSpec); ok && len(spec.Names) == 1 && len(spec.Values) == 1 {
						name := spec.Names[0].Name
						if strings.HasPrefix(name, "Kind") || strings.HasPrefix(name, "Event") {
							if value, ok := stringLiteral(spec.Values[0]); ok && strings.Contains(value, ".") {
								out[value] = true
							}
						}
					}
					if call, ok := node.(*ast.CallExpr); ok && len(call.Args) > 0 {
						if selector, ok := call.Fun.(*ast.SelectorExpr); ok {
							if selector.Sel.Name == "OnEvent" || selector.Sel.Name == "publish" {
								if value, ok := stringLiteral(call.Args[0]); ok && strings.Contains(value, ".") {
									out[value] = true
								}
							}
						}
					}
					return true
				})
			}
		}
	}
	return nil
}

func stringLiteral(expr ast.Expr) (string, bool) {
	literal, ok := expr.(*ast.BasicLit)
	if !ok || literal.Kind != token.STRING {
		return "", false
	}
	var value string
	if json.Unmarshal([]byte(literal.Value), &value) != nil {
		return "", false
	}
	return value, true
}

// methodNames collects every `MethodName` constant from a Go package. It takes
// a DIRECTORY — or, for a caller that means one file, a file — because a
// plane's method names live beside its handlers, not in one shared file:
// internal/protocol/method.go is already past the repository's 1000-line line
// (SIZE1), and appending each new slice's constants to it would be a change
// that pushes a broken file further broken. Reading the package keeps the
// generator's input where the reader of the plane already looks, and the
// result is identical: the same constants, sorted, deduplicated.
func methodNames(path string) ([]string, error) {
	files, err := goFilesOf(path)
	if err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no Go files found in %s", path)
	}
	var names []string
	seen := map[string]bool{}
	for _, file := range files {
		ast.Inspect(file, func(node ast.Node) bool {
			spec, ok := node.(*ast.ValueSpec)
			if !ok || len(spec.Names) != 1 || len(spec.Values) != 1 {
				return true
			}
			typeName, ok := spec.Type.(*ast.Ident)
			if !ok || typeName.Name != "MethodName" {
				return true
			}
			literal, ok := spec.Values[0].(*ast.BasicLit)
			if ok && literal.Kind == token.STRING {
				var name string
				if json.Unmarshal([]byte(literal.Value), &name) == nil && !seen[name] {
					seen[name] = true
					names = append(names, name)
				}
			}
			return true
		})
	}
	sort.Strings(names)
	if len(names) == 0 {
		return nil, fmt.Errorf("no method names found in %s", path)
	}
	return names, nil
}

// goFilesOf parses the non-test Go files of a directory, or one named file. A
// file stays supported because a test that wants to mutate exactly one file
// should not have to copy a package to do it.
func goFilesOf(path string) ([]*ast.File, error) {
	info, err := os.Stat(path)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	if !info.IsDir() {
		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return nil, err
		}
		return []*ast.File{file}, nil
	}
	packages, err := parser.ParseDir(fset, path, func(entry os.FileInfo) bool {
		return strings.HasSuffix(entry.Name(), ".go") && !strings.HasSuffix(entry.Name(), "_test.go")
	}, 0)
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	for _, pkg := range packages {
		for _, name := range slices.Sorted(maps.Keys(pkg.Files)) {
			files = append(files, pkg.Files[name])
		}
	}
	return files, nil
}

func tsType(values []any, indent int) string {
	groups := make(map[string][]any)
	for _, value := range values {
		kind := "null"
		switch value.(type) {
		case string:
			kind = "string"
		case bool:
			kind = "boolean"
		case float64:
			kind = "number"
		case []any:
			kind = "array"
		case map[string]any:
			kind = "object"
		}
		groups[kind] = append(groups[kind], value)
	}
	if len(groups) == 0 {
		return "unknown"
	}
	var parts []string
	for kind, group := range groups {
		switch kind {
		case "object":
			objects := make([]map[string]any, 0, len(group))
			fields := make(map[string][]any)
			for _, value := range group {
				object := value.(map[string]any)
				objects = append(objects, object)
				for key, field := range object {
					fields[key] = append(fields[key], field)
				}
			}
			if len(fields) == 0 {
				parts = append(parts, "Record<string, never>")
				break
			}
			var keys []string
			for key := range fields {
				keys = append(keys, key)
			}
			sort.Strings(keys)
			var lines []string
			for _, key := range keys {
				optional := ""
				if len(fields[key]) < len(objects) {
					optional = "?"
				}
				lines = append(lines, fmt.Sprintf("%s%q%s: %s;", strings.Repeat(" ", indent+2), key, optional, tsType(fields[key], indent+2)))
			}
			parts = append(parts, "{\n"+strings.Join(lines, "\n")+"\n"+strings.Repeat(" ", indent)+"}")
		case "array":
			var elements []any
			for _, value := range group {
				elements = append(elements, value.([]any)...)
			}
			parts = append(parts, "Array<"+tsType(elements, indent)+">")
		default:
			parts = append(parts, kind)
		}
	}
	sort.Strings(parts)
	return strings.Join(parts, " | ")
}
